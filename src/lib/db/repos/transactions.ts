import { isCurrencyCode } from "../../../constants/currencies";
import { newId } from "../../ids";
import type { CategoryKind, Db, Transaction, TransactionType } from "../types";
import { nullable } from "../types";

type TransactionRow = {
  id: string;
  type: TransactionType;
  amount_minor: number;
  currency: string;
  account_id: string;
  transfer_account_id: string | null;
  category_id: string | null;
  item_name: string | null;
  place: string | null;
  note: string | null;
  occurred_at: string;
  local_date: string;
  recurring_id: string | null;
  created_at: string;
  updated_at: string;
};

const COLUMNS = `id, type, amount_minor, currency, account_id, transfer_account_id,
                 category_id, item_name, place, note, occurred_at, local_date,
                 recurring_id, created_at, updated_at`;

const SELECT = `SELECT ${COLUMNS} FROM transactions`;

/** Search joins categories for its name, so every column must be qualified. */
const SELECT_WITH_CATEGORY = `SELECT ${COLUMNS.split(",")
  .map((column) => `t.${column.trim()}`)
  .join(", ")}
  FROM transactions t LEFT JOIN categories c ON c.id = t.category_id`;

function mapTransaction(row: TransactionRow): Transaction {
  return {
    id: row.id,
    type: row.type,
    amountMinor: row.amount_minor,
    currency: row.currency,
    accountId: row.account_id,
    transferAccountId: row.transfer_account_id,
    categoryId: row.category_id,
    itemName: row.item_name,
    place: row.place,
    note: row.note,
    occurredAt: row.occurred_at,
    localDate: row.local_date,
    recurringId: row.recurring_id,
    createdAt: row.created_at,
    updatedAt: row.updated_at,
  };
}

export type NewTransaction = {
  /** Pre-generated by the caller for optimistic inserts; generated here otherwise. */
  id?: string;
  type: TransactionType;
  amountMinor: number;
  currency: string;
  accountId: string;
  transferAccountId?: string | null;
  categoryId?: string | null;
  itemName?: string | null;
  place?: string | null;
  note?: string | null;
  occurredAt: string;
  localDate: string;
  recurringId?: string | null;
};

export type TransactionFilter = {
  currency?: string;
  type?: TransactionType;
  /** Rows where this account is the source or the destination of a transfer. */
  accountId?: string;
  categoryId?: string;
  fromDate?: string;
  toDate?: string;
  /** Only rows with a non-empty note. */
  notePresent?: boolean;
  /**
   * Case-insensitive search over item name, place, note, category name and the
   * amount as the user sees it (12.50, 1.250, 1200).
   */
  text?: string;
  limit?: number;
  offset?: number;
};

function assertAmount(amountMinor: number): void {
  if (!Number.isSafeInteger(amountMinor) || amountMinor <= 0) {
    throw new Error("amount_minor must be a positive integer in the currency's minor unit");
  }
}

function buildFilter(filter: TransactionFilter): { where: string; params: (string | number)[] } {
  const clauses: string[] = [];
  const params: (string | number)[] = [];

  if (filter.currency) {
    clauses.push("t.currency = ?");
    params.push(filter.currency.toUpperCase());
  }
  if (filter.type) {
    clauses.push("t.type = ?");
    params.push(filter.type);
  }
  if (filter.accountId) {
    // An account filter is a ledger view: a transfer out of and into the account
    // both belong to its history.
    clauses.push("(t.account_id = ? OR t.transfer_account_id = ?)");
    params.push(filter.accountId, filter.accountId);
  }
  if (filter.categoryId) {
    clauses.push("t.category_id = ?");
    params.push(filter.categoryId);
  }
  if (filter.fromDate) {
    clauses.push("t.local_date >= ?");
    params.push(filter.fromDate);
  }
  if (filter.toDate) {
    clauses.push("t.local_date <= ?");
    params.push(filter.toDate);
  }
  if (filter.notePresent) {
    clauses.push("(t.note IS NOT NULL AND trim(t.note) <> '')");
  }
  if (filter.text?.trim()) {
    const needle = filter.text.trim().toLowerCase();
    const like = `%${needle}%`;
    const parts = [
      "lower(t.item_name) LIKE ?",
      "lower(t.place) LIKE ?",
      "lower(t.note) LIKE ?",
      "lower(c.name) LIKE ?",
    ];
    const textParams: (string | number)[] = [like, like, like, like];

    // Amounts are stored as minor units, but people search what they read:
    // "12.50" for USD, "1.250" for KWD and "1200" for JPY. Match both the raw
    // minor integer and the common 0/2/3-decimal renderings rather than picking
    // one exponent from the query. Grouping commas are ignored.
    const amountNeedle = filter.text.replace(/[^\d.-]/g, "").replace(/,/g, "");
    if (/\d/.test(amountNeedle)) {
      const amountLike = `%${amountNeedle}%`;
      parts.push(
        "CAST(t.amount_minor AS TEXT) LIKE ?",
        "printf('%.0f', t.amount_minor) LIKE ?",
        "printf('%.2f', t.amount_minor / 100.0) LIKE ?",
        "printf('%.3f', t.amount_minor / 1000.0) LIKE ?",
      );
      textParams.push(amountLike, amountLike, amountLike, amountLike);
    }

    clauses.push(`(${parts.join(" OR ")})`);
    params.push(...textParams);
  }

  return { where: clauses.length ? `WHERE ${clauses.join(" AND ")}` : "", params };
}

export async function listTransactions(
  db: Db,
  filter: TransactionFilter = {},
): Promise<Transaction[]> {
  const { where, params } = buildFilter(filter);
  const limit = Math.max(1, Math.min(5_000, Math.trunc(filter.limit ?? 100)));
  const offset = Math.max(0, Math.trunc(filter.offset ?? 0));

  const rows = await db.getAllAsync<TransactionRow>(
    `${SELECT_WITH_CATEGORY}
     ${where}
     ORDER BY t.local_date DESC, t.occurred_at DESC
     LIMIT ? OFFSET ?`,
    [...params, limit, offset],
  );
  return rows.map(mapTransaction);
}

export async function getTransaction(db: Db, id: string): Promise<Transaction | null> {
  const row = await db.getFirstAsync<TransactionRow>(`${SELECT} WHERE id = ?`, [id]);
  return row ? mapTransaction(row) : null;
}

export async function createTransaction(db: Db, input: NewTransaction): Promise<Transaction> {
  assertAmount(input.amountMinor);
  if (!isCurrencyCode(input.currency)) throw new Error(`Unknown currency: ${input.currency}`);
  if (input.type === "transfer" && !input.transferAccountId) {
    throw new Error("A transfer needs a destination account");
  }

  const id = input.id ?? newId();
  const now = new Date().toISOString();

  await db.runAsync(
    `INSERT INTO transactions (id, type, amount_minor, currency, account_id, transfer_account_id,
                               category_id, item_name, place, note, occurred_at, local_date,
                               recurring_id, created_at, updated_at)
     VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)`,
    [
      id,
      input.type,
      Math.trunc(input.amountMinor),
      input.currency.toUpperCase(),
      input.accountId,
      input.type === "transfer" ? input.transferAccountId! : null,
      nullable(input.categoryId ?? null),
      nullable(input.itemName ?? null),
      nullable(input.place ?? null),
      nullable(input.note ?? null),
      input.occurredAt,
      input.localDate,
      input.recurringId ?? null,
      now,
      now,
    ],
  );

  return (await getTransaction(db, id))!;
}

/**
 * Fields the edit sheet may change. Type and currency are deliberately absent:
 * both are snapshotted when the row is created (02 rule 6), so an edit cannot
 * silently move an old entry into another currency or transaction kind.
 */
export type TransactionPatch = {
  amountMinor?: number;
  accountId?: string;
  transferAccountId?: string | null;
  categoryId?: string | null;
  itemName?: string | null;
  place?: string | null;
  note?: string | null;
  occurredAt?: string;
  localDate?: string;
};

export async function updateTransaction(
  db: Db,
  id: string,
  patch: TransactionPatch,
): Promise<void> {
  const current = await getTransaction(db, id);
  if (!current) throw new Error(`Transaction not found: ${id}`);

  if (patch.amountMinor !== undefined) assertAmount(patch.amountMinor);

  const nextAccountId = patch.accountId ?? current.accountId;
  const nextTransferAccountId =
    current.type === "transfer"
      ? patch.transferAccountId === undefined
        ? current.transferAccountId
        : patch.transferAccountId
      : null;

  if (current.type === "transfer") {
    if (!nextTransferAccountId) {
      throw new Error("A transfer needs a destination account");
    }
    if (nextTransferAccountId === nextAccountId) {
      throw new Error("A transfer needs two different accounts");
    }
  }

  // The pickers already filter by currency, but the repository is the last line of
  // defence: a row's currency snapshot and its accounts must stay in agreement.
  const accountIds = [nextAccountId, nextTransferAccountId].filter(
    (accountId): accountId is string => Boolean(accountId),
  );
  for (const accountId of accountIds) {
    const account = await db.getFirstAsync<{ currency: string }>(
      "SELECT currency FROM accounts WHERE id = ?",
      [accountId],
    );
    if (!account) throw new Error(`Account not found: ${accountId}`);
    if (account.currency.toUpperCase() !== current.currency.toUpperCase()) {
      throw new Error("An account must use the transaction's currency");
    }
  }

  await db.runAsync(
    `UPDATE transactions
        SET amount_minor = ?, account_id = ?, transfer_account_id = ?, category_id = ?,
            item_name = ?, place = ?, note = ?, occurred_at = ?, local_date = ?,
            updated_at = ?
      WHERE id = ?`,
    [
      Math.trunc(patch.amountMinor ?? current.amountMinor),
      nextAccountId,
      nextTransferAccountId,
      patch.categoryId === undefined ? current.categoryId : nullable(patch.categoryId),
      patch.itemName === undefined ? current.itemName : nullable(patch.itemName),
      patch.place === undefined ? current.place : nullable(patch.place),
      patch.note === undefined ? current.note : nullable(patch.note),
      patch.occurredAt ?? current.occurredAt,
      patch.localDate ?? current.localDate,
      new Date().toISOString(),
      id,
    ],
  );
}

export async function deleteTransaction(db: Db, id: string): Promise<void> {
  await db.runAsync("DELETE FROM transactions WHERE id = ?", [id]);
}

/**
 * Total spent for one currency in a date window. Transfers are excluded (02 rule 6)
 * and rows in another currency are never added in — that is the whole point of the
 * `currency` snapshot.
 */
export async function sumSpent(
  db: Db,
  options: { currency: string; fromDate: string; toDate: string; categoryId?: string },
): Promise<number> {
  const params: (string | number)[] = [
    options.currency.toUpperCase(),
    options.fromDate,
    options.toDate,
  ];
  let categoryClause = "";
  if (options.categoryId) {
    categoryClause = "AND category_id = ?";
    params.push(options.categoryId);
  }

  const row = await db.getFirstAsync<{ total: number }>(
    `SELECT COALESCE(SUM(amount_minor), 0) AS total
       FROM transactions
      WHERE type = 'expense' AND currency = ? AND local_date BETWEEN ? AND ? ${categoryClause}`,
    params,
  );
  return row?.total ?? 0;
}

export async function countTransactions(db: Db): Promise<number> {
  const row = await db.getFirstAsync<{ count: number }>("SELECT COUNT(*) AS count FROM transactions");
  return row?.count ?? 0;
}

/** Currencies present in the data, for the "12 entries in USD are not included" note. */
export async function listCurrenciesInUse(db: Db): Promise<{ currency: string; count: number }[]> {
  return db.getAllAsync<{ currency: string; count: number }>(
    "SELECT currency, COUNT(*) AS count FROM transactions GROUP BY currency ORDER BY count DESC",
  );
}

/**
 * Up to five names the user typed recently, grouped case-insensitively. Feeds the
 * recent-name chips; unnamed rows are excluded rather than surfaced as blanks.
 */
export async function listRecentItemNames(
  db: Db,
  options: { currency: string; sinceIso: string; limit?: number },
): Promise<string[]> {
  const rows = await db.getAllAsync<{ item_name: string }>(
    `SELECT item_name
       FROM transactions
      WHERE item_name IS NOT NULL AND item_name <> ''
        AND currency = ? AND local_date >= ?
      GROUP BY lower(item_name)
      ORDER BY MAX(created_at) DESC
      LIMIT ?`,
    [options.currency.toUpperCase(), options.sinceIso, options.limit ?? 5],
  );
  return rows.map((row) => row.item_name);
}

/**
 * Category ids ordered by their most recent use, for the chip row's "recent
 * categories first" rule. Categories never used simply fall back to sort order in
 * the form. Scoped to the active currency and kind so an income chip does not point
 * at an expense category.
 */
export async function listRecentCategoryIds(
  db: Db,
  options: { kind: CategoryKind; currency?: string; limit?: number },
): Promise<string[]> {
  const params: (string | number)[] = [options.kind];
  let currencyClause = "";
  if (options.currency) {
    currencyClause = "AND currency = ?";
    params.push(options.currency.toUpperCase());
  }
  params.push(Math.max(1, Math.min(20, Math.trunc(options.limit ?? 4))));

  const rows = await db.getAllAsync<{ category_id: string }>(
    `SELECT category_id
       FROM transactions
      WHERE category_id IS NOT NULL AND type = ? ${currencyClause}
      GROUP BY category_id
      ORDER BY MAX(created_at) DESC
      LIMIT ?`,
    params,
  );
  return rows.map((row) => row.category_id);
}

/**
 * Put back a row that was just deleted, keeping its original id and timestamps so
 * undo restores exactly what the user saw (09 flow 4).
 */
export async function restoreTransaction(db: Db, transaction: Transaction): Promise<void> {
  await db.runAsync(
    `INSERT OR REPLACE INTO transactions
       (id, type, amount_minor, currency, account_id, transfer_account_id, category_id,
        item_name, place, note, occurred_at, local_date, recurring_id, created_at, updated_at)
     VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)`,
    [
      transaction.id,
      transaction.type,
      transaction.amountMinor,
      transaction.currency,
      transaction.accountId,
      transaction.transferAccountId,
      transaction.categoryId,
      transaction.itemName,
      transaction.place,
      transaction.note,
      transaction.occurredAt,
      transaction.localDate,
      transaction.recurringId,
      transaction.createdAt,
      transaction.updatedAt,
    ],
  );
}

export type CategorySpendRow = {
  /** null = spend that never got a category; still part of the total. */
  categoryId: string | null;
  spentMinor: number;
};

/**
 * Expense totals per category for one currency and window. Feeds the budget rows;
 * transfers and other currencies are excluded by the same rules as `sumSpent`.
 */
export async function sumSpentByCategory(
  db: Db,
  options: { currency: string; fromDate: string; toDate: string },
): Promise<CategorySpendRow[]> {
  const rows = await db.getAllAsync<{ category_id: string | null; spent_minor: number }>(
    `SELECT category_id, COALESCE(SUM(amount_minor), 0) AS spent_minor
       FROM transactions
      WHERE type = 'expense' AND currency = ? AND local_date BETWEEN ? AND ?
      GROUP BY category_id`,
    [options.currency.toUpperCase(), options.fromDate, options.toDate],
  );
  return rows.map((row) => ({
    categoryId: row.category_id,
    spentMinor: row.spent_minor ?? 0,
  }));
}

/**
 * Expense rows in the window that are *not* in the active currency, so Home can
 * say "12 entries in EUR are not included" instead of silently converting them.
 */
export async function countSpentInOtherCurrencies(
  db: Db,
  options: { currency: string; fromDate: string; toDate: string },
): Promise<{ currency: string; count: number }[]> {
  return db.getAllAsync<{ currency: string; count: number }>(
    `SELECT currency, COUNT(*) AS count
       FROM transactions
      WHERE type = 'expense' AND currency <> ? AND local_date BETWEEN ? AND ?
      GROUP BY currency
      ORDER BY count DESC`,
    [options.currency.toUpperCase(), options.fromDate, options.toDate],
  );
}

/** Earliest day with data, so the month selector cannot walk past the first entry. */
export async function earliestLocalDate(db: Db): Promise<string | null> {
  const row = await db.getFirstAsync<{ earliest: string | null }>(
    "SELECT MIN(local_date) AS earliest FROM transactions",
  );
  return row?.earliest ?? null;
}
